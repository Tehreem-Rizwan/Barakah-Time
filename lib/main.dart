const Duration _initTimeout = Duration(seconds: 15);

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Draw behind transparent status/navigation bars (no grey scrim).
  unawaited(SystemChrome.setEnabledSystemUIMode(SystemUiMode.edgeToEdge));
  SystemChrome.setSystemUIOverlayStyle(AppTheme.overlayOnLight);

  // Phone UI is portrait-only.
  unawaited(
    SystemChrome.setPreferredOrientations(const [
      DeviceOrientation.portraitUp,
      DeviceOrientation.portraitDown,
    ]),
  );

  await Hive.initFlutter();
  Hive.registerAdapter(SpiritualActivityAdapter());
  Hive.registerAdapter(SavedVerseAdapter());
  AppInitStatus.hiveReady = true;


  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    ).timeout(_initTimeout);
    AppInitStatus.firebaseReady = true;
  } catch (e, st) {
    // A hot restart re-runs main() with the default app already created.
    AppInitStatus.firebaseReady = Firebase.apps.isNotEmpty;
    if (!AppInitStatus.firebaseReady) {
      debugPrint('Firebase initialization failed: $e\n$st');
    }
  }

  // Initialize Google Sign In (required for v7.0.0+).
  try {
    String? clientId;
    if (!kIsWeb) {
      if (defaultTargetPlatform == TargetPlatform.iOS) {
        clientId = DefaultFirebaseOptions.ios.iosClientId;
      } else if (defaultTargetPlatform == TargetPlatform.macOS) {
        clientId = DefaultFirebaseOptions.macos.iosClientId;
      }
    }
    await GoogleSignIn.instance
        .initialize(clientId: clientId)
        .timeout(_initTimeout);
    AppInitStatus.googleSignInReady = true;
  } catch (e, st) {
    debugPrint('Google Sign-In initialization failed: $e\n$st');
  }

 

  await di.init();

  // Notifications: initialise without blocking first frame.
  unawaited(di.sl<NotificationService>().init());

  runApp(const BarakahTimeApp());
}

class BarakahTimeApp extends StatelessWidget {
  const BarakahTimeApp({super.key});

  @override
  Widget build(BuildContext context) {
    return ScreenUtilInit(
      designSize: const Size(390, 844),
      minTextAdapt: true,
      splitScreenMode: true,
      builder: (context, child) {
        return MultiBlocProvider(
          providers: [
            // Settings first: it reads SharedPreferences synchronously in its
            // constructor, so the blocs below start from the saved settings.
            BlocProvider(
              lazy: false,
              create: (_) => di.sl<SettingsBloc>()..add(LoadSettings()),
            ),
            BlocProvider(
              lazy: false,
              create:
                  (ctx) =>
                      di.sl<PrayerBloc>()..add(
                        LoadPrayerTimes(
                          PrayerConfig.fromSettings(
                            ctx.read<SettingsBloc>().state,
                          ),
                        ),
                      ),
            ),
            BlocProvider(
              lazy: false,
              create: (ctx) {
                final bloc = di.sl<LocationBloc>();
                syncLocationWithSettings(bloc, ctx.read<SettingsBloc>().state);
                return bloc;
              },
            ),
            BlocProvider(
              create: (_) => di.sl<PulseBloc>()..add(LoadPulseData()),
            ),
            BlocProvider(
              create:
                  (ctx) =>
                      di.sl<QuranBloc>()..add(
                        LoadSurahs(
                          languageCode:
                              ctx.read<SettingsBloc>().state.languageCode,
                        ),
                      ),
            ),
            BlocProvider(
              create: (_) => di.sl<AuthBloc>()..add(AuthCheckRequested()),
            ),
          ],
          child: _AppCoordinator(
            child: BlocBuilder<SettingsBloc, SettingsState>(
              buildWhen: (p, c) => p.languageCode != c.languageCode,
              builder: (context, state) {
                return MaterialApp(
                  title: 'Barakah Time',
                  debugShowCheckedModeBanner: false,
                  theme: AppTheme.dark(Locale(state.languageCode)),
                  locale: Locale(state.languageCode),
                  supportedLocales: const [
                    Locale('en'),
                    Locale('ar'),
                    Locale('fa'),
                    Locale('ur'),
                    Locale('tr'),
                  ],
                  localizationsDelegates: const [
                    AppLocalizationsDelegate(),
                    GlobalMaterialLocalizations.delegate,
                    GlobalWidgetsLocalizations.delegate,
                    GlobalCupertinoLocalizations.delegate,
                  ],
                  home: const SplashPage(),
                );
              },
            ),
          ),
        );
      },
    );
  }
}


class _AppCoordinator extends StatefulWidget {
  final Widget child;
  const _AppCoordinator({required this.child});

  @override
  State<_AppCoordinator> createState() => _AppCoordinatorState();
}

class _AppCoordinatorState extends State<_AppCoordinator> {
  late final AppLifecycleListener _lifecycle;

  String? _syncedUid;

  @override
  void initState() {
    super.initState();
    _lifecycle = AppLifecycleListener(
      onResume: _onResume,
      // Send debounced counter changes before the OS may kill the app.
      onPause: () {
        if (di.sl.isRegistered<QazaRepository>()) di.sl<QazaRepository>().flush();
        if (di.sl.isRegistered<TasbeehRepository>()) {
          di.sl<TasbeehRepository>().flush();
        }
      },
    );
    // A permission revoked in system settings kills the process, so check
    // on cold start too (onResume doesn't fire for the first launch).
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        context.read<SettingsBloc>().add(const RecheckNotificationPermission());
      }
    });
  }

  @override
  void dispose() {
    _lifecycle.dispose();
    super.dispose();
  }

  void _onResume() {
    if (!mounted) return;
    context.read<SettingsBloc>().add(const RecheckNotificationPermission());
    final auth = context.read<AuthBloc>();
    auth.add(RefreshSession());
  
    context.read<PrayerBloc>().add(RefreshPrayerTimes());
    _reschedule();
    final state = auth.state;
    if (state is Authenticated && _syncedUid != state.user.id) {
      _syncUser(state.user.id); // retry a sync that failed (e.g. offline)
    }
  }

  void _reschedule() {
    final settings = context.read<SettingsBloc>().state;
    _updateHomeWidget(settings);
    final notifications = di.sl<NotificationService>();
    if (!settings.notificationsEnabled) {
      notifications.cancelAll();
      return;
    }
    final prayer = context.read<PrayerBloc>().state;
    if (prayer is! PrayerLoaded) return;
    final days = di.sl<AdhanService>().timesForDays(
      prayer.latitude,
      prayer.longitude,
      DateTime.now(),
      NotificationService.daysAhead,
      method: settings.calculationMethod,
      madhab: settings.asrMadhab,
    );
    notifications.schedulePrayerNotifications(
      days,
      languageCode: settings.languageCode,
      adhanSound: settings.adhanSoundEnabled,
    );
    di.sl<RamadanService>().reschedule(
      notifications,
      days,
      settings.languageCode,
    );
    di.sl<MemorialReminderService>().reschedule(
      notifications,
      settings.languageCode,
    );
  }

  /// Keeps the home-screen widget's week of prayer times current.
  void _updateHomeWidget(SettingsState settings) {
    final prayer = context.read<PrayerBloc>().state;
    if (prayer is! PrayerLoaded || !di.sl.isRegistered<HomeWidgetService>()) {
      return;
    }
    final days = di.sl<AdhanService>().timesForDays(
      prayer.latitude,
      prayer.longitude,
      DateTime.now(),
      HomeWidgetService.daysAhead,
      method: settings.calculationMethod,
      madhab: settings.asrMadhab,
    );
    di.sl<HomeWidgetService>().update(
      days,
      AppLocalizations(Locale(settings.languageCode)),
    );
  }

  Future<void> _syncUser(String uid) async {
    final pulse = context.read<PulseBloc>();
    final settings = context.read<SettingsBloc>();
    final refreshed = await di.sl<UserDataSyncService>().syncOnSignIn(uid);
    if (!mounted) return;
    final auth = context.read<AuthBloc>().state;
    if (auth is! Authenticated || auth.user.id != uid) return;
    if (refreshed) {
      _syncedUid = uid;
      pulse.add(LoadPulseData());
      settings.add(LoadSettings());
    }
  }

  @override
  Widget build(BuildContext context) {
    return MultiBlocListener(
      listeners: [
        BlocListener<SettingsBloc, SettingsState>(
          listenWhen:
              (p, c) =>
                  PrayerConfig.fromSettings(p) != PrayerConfig.fromSettings(c),
          listener: (context, state) {
            context.read<PrayerBloc>().add(
              LoadPrayerTimes(PrayerConfig.fromSettings(state)),
            );
          },
        ),
        BlocListener<SettingsBloc, SettingsState>(
          listenWhen:
              (p, c) =>
                  p.useAutoLocation != c.useAutoLocation ||
                  (!c.useAutoLocation &&
                      (p.manualLocation != c.manualLocation ||
                          p.manualLatitude != c.manualLatitude ||
                          p.manualLongitude != c.manualLongitude)),
          listener:
              (context, state) =>
                  syncLocationWithSettings(context.read<LocationBloc>(), state),
        ),
        BlocListener<SettingsBloc, SettingsState>(
          listenWhen:
              (p, c) =>
                  p.notificationsEnabled != c.notificationsEnabled ||
                  p.adhanSoundEnabled != c.adhanSoundEnabled ||
                  p.languageCode != c.languageCode,
          listener: (context, _) => _reschedule(),
        ),
        BlocListener<SettingsBloc, SettingsState>(
          listenWhen: (p, c) => p.languageCode != c.languageCode,
          listener:
              (context, state) => context.read<QuranBloc>().add(
                ChangeQuranLanguage(state.languageCode),
              ),
        ),
        BlocListener<PrayerBloc, PrayerState>(
          listenWhen: (_, c) => c is PrayerLoaded,
          listener: (context, _) => _reschedule(),
        ),
        BlocListener<AuthBloc, AuthState>(
          listenWhen:
              (p, c) =>
                  (c is Authenticated &&
                      (p is! Authenticated || p.user.id != c.user.id)) ||
                  (p is Authenticated && c is! Authenticated),
          listener: (context, state) {
            if (state is Authenticated) {
              _syncUser(state.user.id);
            } else if (state is Unauthenticated || state is GuestMode) {
              // Local per-user data was wiped: show the empty state.
              _syncedUid = null;
              context.read<PulseBloc>().add(LoadPulseData());
            }
          },
        ),
      ],
      child: widget.child,
    );
  }
}
